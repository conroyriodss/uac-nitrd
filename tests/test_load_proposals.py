"""Integration: engine proposals wired into the sandboxed write store.

Uses the REAL fixture (480 projects) and the REAL committed RePORTER text cache
(for snapshot hashes). Proposals are synthetic (generated by a stub that mimics
what the engine will produce) — no held-out key is read.
"""
import csv
import hashlib
import json
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tools"))
from engine.inputs import load_project_refs  # noqa: E402
from store import Actor, Rejected, SandboxStore  # noqa: E402
import load_proposals as lp  # noqa: E402

FIXTURE = ROOT / "fixtures" / "UAC_Uncoded_12-01-2025-updated-NIH_ODSS.csv"
CACHE = ROOT / "cache" / "reporter" / "reporter_text.v1.jsonl"
CODER = Actor("coder1", "coder")
CODES = ("ACNS", "AI", "CHuman", "CNPS", "CSP", "EdW", "EHCS", "ENIT", "HCIA", "IRAS", "LSDMA", "SPSQ")


def _synthetic_proposals(refs, cache_path, tmp):
    """Write a proposals.csv and explanations.jsonl from identity + scope codes only."""
    snaps = lp._snapshot_map(cache_path)
    props, expls = tmp / "proposals.csv", tmp / "explanations.jsonl"
    with props.open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["appl_id", "primary_pca", "ai_relevant", "sub_pca"])
        lines = []
        for i, r in enumerate(sorted(refs, key=lambda r: r.appl_id)):
            snap = snaps.get(r.appl_id, "")
            if not snap or snap == hashlib.sha256(f"no-cache:{r.appl_id}".encode()).hexdigest():
                # abstain: no public text
                w.writerow([r.appl_id, "", "false", ""])
                lines.append(json.dumps({"appl_id": r.appl_id, "abstain_reason": "no_public_text: not in cache",
                                         "ranked": []}) + "\n")
            else:
                code = CODES[i % len(CODES)]
                ai = code == "AI" or i % 3 == 0
                sub = "AW" if code == "ACNS" and i % 7 == 0 else ""
                w.writerow([r.appl_id, code, str(ai).lower(), sub])
                lines.append(json.dumps({"appl_id": r.appl_id, "text_sha256": snap,
                                         "primary_pca": code, "ai_relevant": ai, "sub_pca": sub,
                                         "ranked": [{"pca": code, "score": 2.5 + (i % 10) * 0.1}],
                                         "rules_applied": ["test"], "ai_evidence": [],
                                         "abstain_reason": None}) + "\n")
        expls.write_text("".join(lines))
    return props, expls


@pytest.fixture
def env(tmp_path):
    refs = load_project_refs(FIXTURE)
    props, expls = _synthetic_proposals(refs, CACHE, tmp_path)
    listing = lp.build_listing(FIXTURE, CACHE, None)
    return refs, props, expls, listing, tmp_path


def test_listing_covers_all_480_with_cache_snapshots(env):
    refs, _, _, listing, _ = env
    assert len(listing.projects) == 480 == len(refs)
    snaps = lp._snapshot_map(CACHE)
    cached = sum(1 for p in listing.projects if p.snapshot_sha == snaps.get(p.appl_id))
    assert cached == 480  # every project has a cache record (even the 2 not_found ones)
    # amounts come from the cache's award_amount (RePORTER public field); 2 not_found have 0
    amts = lp._cache_amounts(CACHE)
    with_amt = sum(1 for p in listing.projects if p.amount > 0)
    assert with_amt == len(amts)  # every found project has a real amount
    zero = sum(1 for p in listing.projects if p.amount == 0)
    assert zero == 2  # the 2 not_found projects


def test_all_proposals_reach_the_store(env):
    refs, props, expls, listing, tmp = env
    store = SandboxStore(tmp / "sb", authorized_coders={"coder1"}, siacb_members={"board1"})
    store.load_listing(listing)
    result = lp.load_proposals(store, props, expls)
    # every proposal from the CSV either proposed, rejected or abstained
    assert result["total"] == 480
    assert result["proposed"] + result["rejected"] + result["abstained"] == 480
    assert result["abstained"] >= 0  # synthetic stub; the real engine will abstain on no-text projects
    # the store has exactly the non-abstained, non-rejected proposals as PENDING
    pending = [p for p in store._proposals.values() if p["status"] == "PENDING"]
    assert len(pending) == result["proposed"]


