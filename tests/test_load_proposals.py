def test_coder_can_approve_a_proposal(env):
    refs, props, expls, listing, tmp = env
    store = SandboxStore(tmp / "sb", authorized_coders={"coder1"}, siacb_members={"board1"})
    store.load_listing(listing)
    result = lp.load_proposals(store, props, expls)
    # pick the first proposed project and approve it
    first = result["proposals"][0]
    pid, appl = first["proposal_id"], first["appl_id"]
    p = store.proposal(pid)
    aid = store.approve(pid, CODER, snapshot_sha=p["snapshot_sha"])
    a = store.assignment(aid)
    assert a["primary_pca"] == first["primary_pca"] and a["approved_by"] == "coder1"
    assert a["provenance"] == "approval" and a["appl_id"] == appl


def test_coder_can_override_a_proposal(env):
    refs, props, expls, listing, tmp = env
    store = SandboxStore(tmp / "sb", authorized_coders={"coder1"}, siacb_members={"board1"})
    store.load_listing(listing)
    result = lp.load_proposals(store, props, expls)
    first = result["proposals"][0]
    pid = first["proposal_id"]
    p = store.proposal(pid)
    aid = store.approve(pid, CODER, snapshot_sha=p["snapshot_sha"],
                        override={"primary_pca": "HCIA", "ai_relevant": True, "sub_pca": ""})
    a = store.assignment(aid)
    assert a["primary_pca"] == "HCIA" and a["proposed"]["primary_pca"] == first["primary_pca"]
    assert a["overridden"] is True


def test_replay_preserves_proposals(env):
    refs, props, expls, listing, tmp = env
    sb = tmp / "sb"
    store = SandboxStore(sb, authorized_coders={"coder1"}, siacb_members={"board1"})
    store.load_listing(listing)
    lp.load_proposals(store, props, expls)
    # replay from the log
    again = SandboxStore.replay(sb, authorized_coders={"coder1"}, siacb_members={"board1"})
    assert again.rollup("NITRD", 2025) == store.rollup("NITRD", 2025)
    assert len(again._proposals) == len(store._proposals)


